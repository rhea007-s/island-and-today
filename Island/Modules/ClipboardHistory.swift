import SwiftUI
import Observation

/// The last thirty things you copied — text only, kept in memory only.
///
/// Never written to disk: a clipboard history is a log of passwords, codes and
/// half-written messages, and quitting the app should forget all of it.
/// Copies a password manager marks as concealed or transient are skipped
/// (the nspasteboard.org convention 1Password, Bitwarden and others follow).
@MainActor
@Observable
final class ClipboardHistory {
    struct Clip: Identifiable, Equatable {
        let id = UUID()
        var text: String
        var app: String?
        var date: Date
    }

    private(set) var items: [Clip] = []
    private(set) var isRunning = false
    /// The clip just copied back from the list, for a moment of "Copied" feedback.
    private(set) var justCopied: UUID?

    private let limit = 30
    private var lastChange = NSPasteboard.general.changeCount
    private var poller: Timer?

    private static let skipped: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]

    func start() {
        guard poller == nil else { return }
        lastChange = NSPasteboard.general.changeCount
        let timer = Timer(timeInterval: 0.6, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.check() }
        }
        timer.tolerance = 0.2
        RunLoop.main.add(timer, forMode: .common)
        poller = timer
        isRunning = true
    }

    func stop() {
        poller?.invalidate()
        poller = nil
        isRunning = false
    }

    private func check() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount

        let types = Set((pb.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.skipped),
              let text = pb.string(forType: .string),
              !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty
        else { return }

        let clip = Clip(text: text, app: NSWorkspace.shared.frontmostApplication?.localizedName, date: Date())
        withAnimation(.spring(response: 0.35, dampingFraction: 1)) {
            items.removeAll { $0.text == text }
            items.insert(clip, at: 0)
            if items.count > limit { items.removeLast(items.count - limit) }
        }
    }

    func copy(_ clip: Clip) {
        let pb = NSPasteboard.general
        pb.clearContents()
        pb.setString(clip.text, forType: .string)
        // Our own write is not a new copy: don't let the poller re-add it as a
        // fresh row (new id) and steal the "Copied" checkmark from this one.
        lastChange = pb.changeCount
        justCopied = clip.id
        Task { @MainActor in
            try? await Task.sleep(for: .seconds(1.2))
            if justCopied == clip.id { justCopied = nil }
        }
    }

    func remove(_ clip: Clip) {
        withAnimation(.spring(response: 0.3, dampingFraction: 1)) { items.removeAll { $0.id == clip.id } }
    }

    func clear() {
        withAnimation(.spring(response: 0.3, dampingFraction: 1)) { items.removeAll() }
    }
}

struct ClipboardTab: View {
    let model: IslandModel
    private var history: ClipboardHistory { model.clipboard }

    var body: some View {
        VStack(alignment: .leading, spacing: 8) {
            HStack {
                Text("Clipboard")
                    .font(.system(size: 15, weight: .bold))
                Text("\(history.items.count)")
                    .font(.system(size: 12, weight: .semibold, design: .rounded))
                    .foregroundStyle(.white.opacity(0.45))
                Spacer()
                if !history.isRunning {
                    Text("Paused in Settings")
                        .font(.system(size: 11, weight: .medium))
                        .foregroundStyle(.white.opacity(0.45))
                }
                if !history.items.isEmpty {
                    Button("Clear") { history.clear() }.buttonStyle(ChipStyle())
                }
            }

            if history.items.isEmpty {
                VStack(spacing: 8) {
                    Image(systemName: "doc.on.clipboard")
                        .font(.system(size: 28, weight: .semibold))
                        .foregroundStyle(.white.opacity(0.3))
                    Text("Copy some text — it lands here.")
                        .font(.system(size: 12))
                        .foregroundStyle(.white.opacity(0.55))
                    Text("Kept in memory only. Passwords from password managers are skipped.")
                        .font(.system(size: 11))
                        .foregroundStyle(.white.opacity(0.35))
                }
                .frame(maxWidth: .infinity, maxHeight: .infinity)
            } else {
                ScrollView {
                    LazyVStack(spacing: 4) {
                        ForEach(history.items) { clip in
                            ClipRow(clip: clip, copied: history.justCopied == clip.id) {
                                history.copy(clip)
                                if model.settings.haptics { Haptics.tap() }
                            } onDelete: {
                                history.remove(clip)
                            }
                            .transition(.move(edge: .top).combined(with: .opacity))
                        }
                    }
                }
                .scrollIndicators(.never)
            }
        }
    }
}

private struct ClipRow: View {
    let clip: ClipboardHistory.Clip
    let copied: Bool
    let onCopy: () -> Void
    let onDelete: () -> Void
    @State private var hovering = false

    var body: some View {
        HStack(alignment: .top, spacing: 10) {
            VStack(alignment: .leading, spacing: 3) {
                Text(clip.text.trimmingCharacters(in: .whitespacesAndNewlines))
                    .font(.system(size: 12.5))
                    .lineLimit(2)
                    .frame(maxWidth: .infinity, alignment: .leading)
                HStack(spacing: 4) {
                    if let app = clip.app { Text(app) }
                    Text("·")
                    Text(clip.date, style: .relative)
                }
                .font(.system(size: 10, weight: .medium))
                .foregroundStyle(.white.opacity(0.4))
            }

            ZStack {
                if copied {
                    Image(systemName: "checkmark.circle.fill")
                        .foregroundStyle(.green)
                        .transition(.scale.combined(with: .opacity))
                } else if hovering {
                    Button(action: onDelete) {
                        Image(systemName: "xmark").font(.system(size: 10, weight: .bold))
                    }
                    .buttonStyle(.plain)
                    .foregroundStyle(.white.opacity(0.5))
                    .transition(.opacity)
                }
            }
            .frame(width: 18)
            .animation(.spring(response: 0.3, dampingFraction: 0.7), value: copied)
        }
        .padding(.horizontal, 10)
        .padding(.vertical, 7)
        .background(RoundedRectangle(cornerRadius: 10, style: .continuous).fill(.white.opacity(hovering ? 0.1 : 0.05)))
        .contentShape(Rectangle())
        .onTapGesture(perform: onCopy)
        .onHover { hovering = $0 }
        .help("Click to copy")
    }
}
